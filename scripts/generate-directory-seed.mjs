/**
 * Generate supabase/migrations/*_seed_catalog_prospects.sql from
 * scripts/seed-source/catalog.ts and prospects.ts (not in the Vite client graph).
 *
 * Usage (from repo root):
 *   node scripts/generate-directory-seed.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(
  root,
  'supabase/migrations/20260802251000_seed_catalog_prospects.sql',
);

function extractExportedArray(source, exportName) {
  const marker = `export const ${exportName}`;
  const start = source.indexOf(marker);
  if (start < 0) throw new Error(`Missing ${exportName}`);
  const assign = source.indexOf('=', start);
  if (assign < 0) throw new Error(`Missing = for ${exportName}`);
  const bracket = source.indexOf('[', assign);
  if (bracket < 0) throw new Error(`Missing array for ${exportName}`);

  let depth = 0;
  let end = -1;
  for (let i = bracket; i < source.length; i++) {
    const ch = source[i];
    if (ch === '[') depth += 1;
    else if (ch === ']') {
      depth -= 1;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end < 0) throw new Error(`Unclosed array for ${exportName}`);
  return new Function(`return (${source.slice(bracket, end)})`)();
}

function sqlStr(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlBool(value) {
  return value ? 'true' : 'false';
}

const catalogSource = readFileSync(join(root, 'scripts/seed-source/catalog.ts'), 'utf8');
const prospectsSource = readFileSync(join(root, 'scripts/seed-source/prospects.ts'), 'utf8');

const catalog = extractExportedArray(catalogSource, 'CATALOG_DATA');
const prospects = extractExportedArray(prospectsSource, 'PROSPECTS_DATA');

const catalogValues = catalog
  .map(
    (item) =>
      `  ((select id from lines where code = 'ogr'), ${item.page}, ${sqlStr(item.cat)}, ${sqlStr(item.sku)}, ${sqlStr(item.name)}, ${sqlStr(item.color)}, ${sqlStr(item.tagline)}, ${Number(item.priceUsd)}, ${Number(item.msrpCad)}, ${sqlBool(item.isNew)}, ${sqlBool(item.isNameDrop)})`,
  )
  .join(',\n');

const prospectValues = prospects
  .map(
    (p) =>
      `  (${p.id}, ${sqlStr(p.name)}, ${sqlStr(p.category)}, ${sqlStr(p.region)}, ${sqlStr(p.city)}, ${sqlStr(p.address)}, ${sqlStr(p.phone)}, ${sqlStr(p.fit)})`,
  )
  .join(',\n');

const sql = `-- Seed catalog_items (OGR) and prospects from former static corpora.
-- Generated by scripts/generate-directory-seed.mjs — do not hand-edit bulk rows.

insert into catalog_items (
  line_id, page, cat, sku, name, color, tagline, price_usd, msrp_cad, is_new, is_name_drop
)
values
${catalogValues}
on conflict (line_id, sku) do update set
  page = excluded.page,
  cat = excluded.cat,
  name = excluded.name,
  color = excluded.color,
  tagline = excluded.tagline,
  price_usd = excluded.price_usd,
  msrp_cad = excluded.msrp_cad,
  is_new = excluded.is_new,
  is_name_drop = excluded.is_name_drop,
  updated_at = now();

insert into prospects (id, name, category, region, city, address, phone, fit)
values
${prospectValues}
on conflict (id) do update set
  name = excluded.name,
  category = excluded.category,
  region = excluded.region,
  city = excluded.city,
  address = excluded.address,
  phone = excluded.phone,
  fit = excluded.fit,
  updated_at = now();
`;

writeFileSync(outPath, sql);
console.log(
  `Wrote ${outPath} (${catalog.length} catalog items, ${prospects.length} prospects)`,
);
